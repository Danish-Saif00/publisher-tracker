export interface ApiHttpErrorOptions {
  readonly cause?: unknown;
}

function createNativeErrorOptions(cause: unknown): ErrorOptions | undefined {
  return cause === undefined
    ? undefined
    : {
        cause,
      };
}

export class ApiHttpError extends Error {
  public constructor(
    public readonly code: ApiHttpErrorCode,
    public readonly statusCode: number,
    message: string,
    options: ApiHttpErrorOptions = {},
  ) {
    const normalizedMessage = message.trim();

    super(
      normalizedMessage.length > 0 ? normalizedMessage : 'The HTTP request is invalid.',
      createNativeErrorOptions(options.cause),
    );

    this.name = 'ApiHttpError';
  }
}
